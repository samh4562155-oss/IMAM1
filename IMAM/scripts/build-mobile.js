'use strict';
// Builds the Capacitor web bundle in ./www from ./public (the same files the web version uses).
// Usage:  IMAM_API_BASE=https://your-imam-server.example.com npm run build:mobile
// Only a public server URL goes into the app. The Deepgram key never leaves the server.
require('dotenv').config();
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'www');
const apiBase = String(process.env.IMAM_API_BASE || '').trim().replace(/\/+$/, '');

if (!/^https:\/\/[^\s/]+/.test(apiBase) && !process.env.IMAM_ALLOW_INSECURE) {
  console.error('\nSet IMAM_API_BASE to your hosted HTTPS server, e.g.\n  IMAM_API_BASE=https://imam.example.com npm run build:mobile\n' +
    '(For local testing only, set IMAM_ALLOW_INSECURE=1 to allow http://.)\n');
  process.exit(1);
}

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(root, 'public'), out, { recursive: true });
fs.mkdirSync(path.join(out, 'lib'), { recursive: true });
fs.copyFileSync(path.join(root, 'lib', 'prayer.js'), path.join(out, 'lib', 'prayer.js'));
fs.mkdirSync(path.join(out, 'vendor'), { recursive: true });
fs.copyFileSync(path.join(root, 'node_modules', 'three', 'build', 'three.min.js'), path.join(out, 'vendor', 'three.min.js'));
fs.writeFileSync(path.join(out, 'config.js'),
  `// Generated by scripts/build-mobile.js — public settings only, no secrets.\nwindow.IMAM_CONFIG = { apiBase: ${JSON.stringify(apiBase)} };\n`);

// Safety net: refuse to ship anything that looks like the Deepgram key.
const key = process.env.DEEPGRAM_API_KEY;
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
for (const file of walk(out)) {
  const text = fs.readFileSync(file, 'utf8');
  if ((key && key.length > 8 && text.includes(key)) || /DEEPGRAM_API_KEY\s*=/.test(text)) {
    fs.rmSync(out, { recursive: true, force: true });
    console.error('Stopped: a secret was found in ' + path.relative(root, file));
    process.exit(1);
  }
}
console.log(`www/ ready for Capacitor (API: ${apiBase}). Next: npx cap sync android`);
